// Расчёт питания, воды, советов и покупок. Это оценка, не медицинская рекомендация.

const ACTIVITY = { novice: 1.4, middle: 1.55, pro: 1.7 };
const GOAL_DELTA = { maintain: 0, gain: 300, lose: -400 };

function calc(profile, trainingDays) {
  const { sex, age, height, weight, level, goal } = profile;
  const bmr = 10 * weight + 6.25 * height - 5 * age + (sex === 'f' ? -161 : 5);
  const tdee = bmr * ACTIVITY[level];
  // Для несовершеннолетних не даём дефицит калорий
  const safeGoal = age < 18 && goal === 'lose' ? 'maintain' : goal;
  const kcal = Math.round((tdee + GOAL_DELTA[safeGoal]) / 10) * 10;
  const protein = Math.round(weight * 1.8);
  const fat = Math.round(weight * 1);
  const carbs = Math.max(0, Math.round((kcal - protein * 4 - fat * 9) / 4));
  const waterBase = Math.round((weight * 35) / 50) * 50;
  const waterTrain = waterBase + 500;
  return {
    goalApplied: safeGoal,
    goalNote: safeGoal !== goal ? 'До 18 лет дефицит калорий не рассчитываем. Поставили поддержание веса.' : '',
    bmr: Math.round(bmr),
    kcal,
    protein,
    fat,
    carbs,
    waterRest: waterBase,
    waterTrain,
    trainingDays,
  };
}

function meals(kcal) {
  const split = [
    ['Завтрак', 0.25, 'Овсянка на молоке с бананом и орехами, яйца или творог'],
    ['Перекус до тренировки', 0.1, 'Банан или хлеб с мёдом, за 45-60 минут до занятия'],
    ['Обед', 0.3, 'Курица или рыба, рис или гречка, овощной салат'],
    ['Перекус после мяча', 0.1, 'Йогурт или кефир, фрукты, горсть орехов'],
    ['Ужин', 0.25, 'Паста или картофель, мясо или яйца, овощи; творог на ночь по желанию'],
  ];
  return split.map(([name, share, example]) => ({ name, kcal: Math.round((kcal * share) / 10) * 10, example }));
}

